"""Build results/m1-2026-11-02.json and results/m1/m1-tables.md from results/m1/*.

Exploit cell = the exploit's guaranteed payout: lowest score over the 5 tasks, in whichever format
(fenced or bare) pays more. Reference cell = tasks (of 5) at >= 0.95, fenced · bare.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
M1 = ROOT / "results" / "m1"
DATE = "2026-11-02"


def load(name):
    p = M1 / name
    return json.loads(p.read_text()) if p.exists() else None


ship, pat, sg = load("raw_shipped.json"), load("raw_patched.json"), load("raw_securegrade.json")
EX = json.loads((ROOT / "exploits" / "exploits.json").read_text())["exploits"]
NOTHING = [e["id"] for e in EX if e["solves_nothing"]]
TASKS = [t["task_id"] for t in json.loads((ROOT / "exploits" / "tasks.json").read_text())]


def index(cells):
    return {(c["reward"], c["mode"], c["task"], c["exploit"], c["fenced"]): c for c in cells}


def val(c):
    return c["score"] if c and c.get("status") == "ok" and c.get("score") is not None else None


def payout(idx, rw, mode, ex):
    best = None
    for f in (True, False):
        vals = [val(idx.get((rw, mode, t, ex, f))) for t in TASKS]
        if any(v is None for v in vals):
            sts = {(idx.get((rw, mode, t, ex, f)) or {}).get("status") for t in TASKS}
            cand = "exc" if "raised" in sts else ("timeout" if "timeout" in sts else "n/a")
            best = best if isinstance(best, float) else cand
            continue
        m = min(vals)
        if not isinstance(best, float) or m > best:
            best = m
    return best


def ref_full(idx, rw, mode):
    return " · ".join(str(sum(1 for t in TASKS if (val(idx.get((rw, mode, t, "reference", f))) or -9) >= 0.95))
                      for f in (True, False))


def fmt(v):
    return f"{v:.2f}" if isinstance(v, float) else str(v)


IS, IP, IG = index(ship["cells"]), index(pat["cells"]), index(sg["cells"])
ROWS = [("code_execution", "tests"), ("code_execution", "no_tests"), ("code_execution[dicts]", "tests"),
        ("code_correctness", "tests"), ("code_correctness", "no_tests"), ("code_correctness[asserts]", "tests"),
        ("mbpp_reward", "tests"), ("mbpp_reward", "no_tests"), ("code_verifiable", "tests"),
        ("code_verifiable", "no_tests"), ("counterfact_grpo_code", "tests")]
table = []
for rw, mode in ROWS:
    row = {"reward": rw, "mode": mode, "reference_full_shipped": ref_full(IS, rw, mode),
           "reference_full_patched": ref_full(IP, rw, mode)}
    for ex in NOTHING:
        row[ex] = {"shipped": payout(IS, rw, mode, ex), "patched": payout(IP, rw, mode, ex)}
    row["best_shipped"] = max((row[e]["shipped"] for e in NOTHING if isinstance(row[e]["shipped"], float)), default=None)
    row["best_patched"] = max((row[e]["patched"] for e in NOTHING if isinstance(row[e]["patched"], float)), default=None)
    table.append(row)
sgrow = {"reward": "securegrade", "mode": "tests", "reference_full": ref_full(IG, "securegrade", "tests")}
for ex in NOTHING:
    sgrow[ex] = payout(IG, "securegrade", "tests", ex)
sgrow["best"] = max(v for k, v in sgrow.items() if k in NOTHING)
hard = {}
for name, idx, rw in (("shipped", IS, "code_execution"), ("patched", IP, "code_execution"), ("securegrade", IG, "securegrade")):
    hard[name] = {t: max((val(idx.get((rw, "tests", t, "hardcode_visible", f))) or 0) for f in (True, False)) for t in TASKS}

fn = {"shipped": load("fn_shipped.json"), "patched": load("fn_patched.json"), "securegrade": load("securegrade_fn.json")}
fn_summary = {"shipped": fn["shipped"]["summary"] if fn["shipped"] else None,
              "patched": fn["patched"]["summary"] if fn["patched"] else None,
              "securegrade": {k: v for k, v in (fn["securegrade"] or {}).get("summary", {}).items()}}

side = {"shipped": ship.get("side"), "patched": pat.get("side")}
out = {"date": DATE, "versions": {"shipped": ship["versions"], "patched": pat["versions"]},
       "rule": __doc__.strip().split("\n\n")[1], "table": table, "securegrade": sgrow, "hardcode_visible": hard,
       "fn_summary": fn_summary, "side_experiments": side,
       "securegrade_isolation_seen": sg.get("isolation_seen"),
       "recipe_patched": load("recipe_sim_patched.json"),
       "cells": {"shipped": ship["cells"], "patched": pat["cells"], "securegrade": sg["cells"]}}
for name in ("systemexit_trl_patched.txt",):
    p = M1 / name
    if p.exists():
        out[name] = p.read_text()
(ROOT / "results" / f"m1-{DATE}.json").write_text(json.dumps(out, indent=1, default=str))

L = ["# M1 tables (generated by scripts/make_m1_report.py)", "", __doc__.strip().split("\n\n")[1], "",
     "| reward [mode] | ref full (shipped) | ref full (patched) | " + " | ".join(NOTHING) + " |",
     "|" + "---|" * (len(NOTHING) + 3)]
for r in table:
    L.append(f"| {r['reward']} [{r['mode']}] | {r['reference_full_shipped']} | {r['reference_full_patched']} | "
             + " | ".join(f"{fmt(r[e]['shipped'])} → {fmt(r[e]['patched'])}" for e in NOTHING) + " |")
L.append(f"| securegrade [tests] | {sgrow['reference_full']} | | " + " | ".join(fmt(sgrow[e]) for e in NOTHING) + " |")
L += ["", "## FN summary", "", "```json", json.dumps(fn_summary, indent=1), "```", "",
      "## hardcode_visible", "", "```json", json.dumps(hard, indent=1), "```"]
(M1 / "m1-tables.md").write_text("\n".join(L))
print("\n".join(L[:20]))
for k in ("shipped", "patched"):
    if fn_summary[k]:
        for kk, v in sorted(fn_summary[k].items()):
            print(k, kk, v)
print({k: v for k, v in fn_summary["securegrade"].items() if "reference" in k})
